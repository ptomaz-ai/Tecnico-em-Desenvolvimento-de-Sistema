diaSemana = int(input("digite um numero entre 1 e 7"))

if(diaSemana == 1 ):
    print("segunda")
elif(diaSemana == 2):
    print("terça")
elif(diaSemana == 3):
    print("quarta")
elif(diaSemana == 4):
    print("quinta")
elif(diaSemana == 5):
    print("sexta")
elif(diaSemana == 6):
    print("sabado")
elif(diaSemana == 7):
    print("domingo")
else:
    print("dia invalida")    


       